void RestoreInitialData(PesMemory& memory, const std::string& installRoot) {
  std::string error;
  const auto exe = PeImage::Open(installRoot + "/PES2021.exe", &error);
  if (!exe) throw std::runtime_error("PES boot: the install's exe: " + error);
  std::vector<uint8_t> initial(kInitializedDataBytes);
  if (!exe->ReadVa(kInitializedDataVa, initial.size(), initial.data()))
    throw std::runtime_error("PES boot: the install's exe holds no .data at " + std::to_string(kInitializedDataVa));
  const uint8_t* pattern = reinterpret_cast<const uint8_t*>(kEmptyHashMap);
  for (uint64_t at = 0; at + sizeof kEmptyHashMap <= initial.size(); at += sizeof(uint64_t))
    if (std::memcmp(initial.data() + at, pattern, sizeof kEmptyHashMap) == 0)
      std::memcpy(memory.Image() + (kInitializedDataVa - PesMemory::kImageBase) + at, pattern, sizeof kEmptyHashMap);
}

void ResetStaticInitState(PesMemory& memory) {
  const uint8_t* code = memory.Image() + (kCodeSectionVa - PesMemory::kImageBase);
  for (uint64_t at = 0; at + kLeaBytes + kCallBytes <= kCodeSectionBytes; ++at) {
    if (std::memcmp(code + at, kLeaRcxRipOpcode, sizeof kLeaRcxRipOpcode) != 0 || code[at + kLeaBytes] != kCallOpcode) continue;
    int32_t callRel, guardRel;
    std::memcpy(&guardRel, code + at + sizeof kLeaRcxRipOpcode, sizeof guardRel);
    std::memcpy(&callRel, code + at + kLeaBytes + 1, sizeof callRel);
    const uint64_t site = kCodeSectionVa + at;
    if (site + kLeaBytes + kCallBytes + static_cast<int64_t>(callRel) != kInitThreadHeaderVa) continue;
    const uint64_t guard = site + kLeaBytes + static_cast<int64_t>(guardRel);
    std::memset(memory.Image() + (guard - PesMemory::kImageBase), 0, sizeof(uint32_t));
  }
  std::memcpy(memory.Image() + (kInitGlobalEpochVa - PesMemory::kImageBase), &kInitEpochStart, sizeof kInitEpochStart);
}

