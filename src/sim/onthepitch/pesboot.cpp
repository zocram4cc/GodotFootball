void RestoreInitialData(PesMemory& memory, const std::string& installRoot) {
  std::string error;
  const auto exe = PeImage::Open(installRoot + "/PES2021.exe", &error);
  if (!exe) throw std::runtime_error("PES boot: the install's exe: " + error);
  std::vector<uint8_t> initial(kInitializedDataBytes);
  if (!exe->ReadVa(kInitializedDataVa, initial.size(), initial.data()))
    throw std::runtime_error("PES boot: the install's exe holds no .data at " + std::to_string(kInitializedDataVa));
  const uint8_t* pattern = reinterpret_cast<const uint8_t*>(kEmptyHashMap);
  for (uint64_t at = 0; at + sizeof kEmptyHashMap <= initial.size(); at += sizeof(uint64_t))
    if (std::memcmp(initial.data() + at, pattern, sizeof kEmptyHashMap) == 0)
      std::memcpy(memory.Image() + (kInitializedDataVa - PesMemory::kImageBase) + at, pattern, sizeof kEmptyHashMap);
}

void ResetStaticInitState(PesMemory& memory) {
  const uint8_t* code = memory.Image() + (kCodeSectionVa - PesMemory::kImageBase);
  for (uint64_t at = 0; at + kLeaBytes + kCallBytes <= kCodeSectionBytes; ++at) {
    if (std::memcmp(code + at, kLeaRcxRipOpcode, sizeof kLeaRcxRipOpcode) != 0 || code[at + kLeaBytes] != kCallOpcode) continue;
    int32_t callRel, guardRel;
    std::memcpy(&guardRel, code + at + sizeof kLeaRcxRipOpcode, sizeof guardRel);
    std::memcpy(&callRel, code + at + kLeaBytes + 1, sizeof callRel);
    const uint64_t site = kCodeSectionVa + at;
    if (site + kLeaBytes + kCallBytes + static_cast<int64_t>(callRel) != kInitThreadHeaderVa) continue;
    const uint64_t guard = site + kLeaBytes + static_cast<int64_t>(guardRel);
    std::memset(memory.Image() + (guard - PesMemory::kImageBase), 0, sizeof(uint32_t));
  }
  std::memcpy(memory.Image() + (kInitGlobalEpochVa - PesMemory::kImageBase), &kInitEpochStart, sizeof kInitEpochStart);
}

uint64_t PesBoot(PesMemory& memory, const std::string& installRoot) {
  ZeroInitializedData(memory);
  RestoreInitialData(memory, installRoot);
  ResetStaticInitState(memory);
  // The thread-safe static guards (_Init_thread_header) read the thread's TLS block (epoch at +0x84): it exists before the first one runs.
  InstallScratchArena(memory);
  memory.Call(::pes_fn_14038EE80, {});  // malloc_init_hard, as PES's first allocation runs it (FUN_14038E3E0 tests its flag at 0x1436DCEE0)
  const uint64_t initializers = RunStaticInitializers(memory);
  const uint64_t manager = memory.Alloc(kFileManagerBytes);
  memory.Call(::pes_fn_14149A620, {manager});
  memory.Call(::pes_fn_1414A3550, {});
  memory.Call(::pes_fn_1414B08A0, {});
  memory.Call(::pes_fn_1414B0E90, {});
  memory.Call(::pes_fn_1402223C0, {});
  memory.Call(::pes_fn_140222390, {});
  // PES's scripting init (FUN_14029E940, called from the engine init FUN_1402902B0 before any system): the "Lua VM" pool and the script manager
  // DAT_1436D0068 names, which FUN_141B0BA70 pushes a C function into. The dump's manager is the dead game's; the config block's pool size (+4) is
  // zero, which the init reads as its default (0x300000).
  memory.Call(::pes_fn_14029E940, {memory.Alloc(kScriptConfigBytes)});
  // ponytail: FUN_14149AB60 also initialises the CRI library (FUN_14149ABE0) and starts its worker threads (FUN_1414B11A0, FUN_1414B1D90);
  // GF has no CRI library (the six CRI Fs calls under the reader are GF's file seam) and serves the request lists itself (ServeFile), so
  // those three calls are left out. Remove with a GF that runs PES's worker threads.
  memory.Call(::pes_fn_141AE77B0, {kBootArgs[0], kBootArgs[1], kBootArgs[2], kBootArgs[3]});
  return initializers;
}

