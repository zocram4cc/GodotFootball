// FUN_14149AB60: FUN_1403FB410(pool, 0x2E0).
constexpr uint64_t kFileManagerBytes = 0x2E0;
// The first call of the game's boot (live2/pid2740946 seq001): FUN_141AE77B0(0, 1, 0, 0, 0).
constexpr uint64_t kBootArgs[4] = {0, 1, 0, 0};
// The CRT's thread-safe function-local statics (`static T x;` -> _Init_thread_header / _Init_thread_footer): a static is built on its first
// use, while its guard dword is 0. The dump holds the dead game's: 692 of the image's 856 guards are set and their objects hold dead-heap
// state, so a first use here would skip the constructor and walk dead pointers (the string table, the anime type objects). PES starts with
// every guard 0, the global epoch (_Init_global_epoch, DAT_14350B358) at INT_MIN and each thread's epoch (TLS block +0x84, a thread-local
// initialised to INT_MIN) likewise. A guard is the rip-relative operand of the `lea rcx, [guard]` that sits right before each `call
// _Init_thread_header` (0x14159F8B0): the scan finds them in the image's code section (.trace, the section table: 0x140001000, 0x252D800 bytes).
constexpr uint64_t kInitThreadHeaderVa = 0x14159F8B0, kInitGlobalEpochVa = 0x14350B358, kCodeSectionVa = 0x140001000, kCodeSectionBytes = 0x252D800;
constexpr uint32_t kInitEpochStart = 0x80000000u;  // INT_MIN
constexpr uint64_t kTlsInitEpochOffset = 0x84;     // the thread block's epoch
// `lea rcx, [rip + rel32]` (48 8D 0D) directly followed by `call rel32` (E8): 7 + 5 bytes.
constexpr uint8_t kLeaRcxRipOpcode[3] = {0x48, 0x8D, 0x0D}, kCallOpcode = 0xE8;
constexpr uint64_t kLeaBytes = 7, kCallBytes = 5;
// The engine's hash-map statics (the type table, FUN_14026A2B0's, and its siblings) are constant-initialized in the exe's .data: the file holds
// each in its empty state, the six qwords FUN_140266ED0's inlined constructor stores ({0, -1, 0xFFFFFFFF, 0, 0, 0}, 0x14339B010..0x14339B038).
// The dump holds the dead game's filled maps (counts, pointers into its heap) in 9 of the file's 17 such objects. The initialized part of .data
// is the section's raw size (the section table: 0x14339B000, 0x334800 bytes); the install's own exe supplies the bytes (PeImage::ReadVa).
constexpr uint64_t kInitializedDataVa = 0x14339B000, kInitializedDataBytes = 0x334800;
constexpr uint64_t kEmptyHashMap[6] = {0, ~0ull, 0xFFFFFFFFull, 0, 0, 0};
// PES's process start runs C++ static initializers (a run of code pointers at 0x142530868.., 6,849 set; it is a mixed run: it also holds CRT
// entries such as atexit, so only the entries the selector picks run). The dump holds their results with the dead game's runtime mutations on
// top (a std::map's head node, an intrusive pointer global naming a dead object). kSelectedInitializers (pesinitializers.inc, generated by
// tools/dev/translate/select_initializers.py) lists, in table order, those that store to a global a translated function names; the boot runs
// the ones the layer holds. The selection grows with the layer (a fixed point is reached when every selected initializer is translated).
// FUN_14029E940's config block: it reads only the dword at +4 (the pool size, 0 = default).
constexpr uint64_t kScriptConfigBytes = 0x10;
// The scratch arena (FUN_1403EFDF0 pushes frames on the TLS slot's frame): the thread block's TLS pointer (TEB+0x58), the TLS index cell, the
// slot offset in the thread's block, the frame's vtable and the arena's size.
constexpr uint64_t kTebTlsPointerOffset = 0x58, kTlsIndexVa = 0x1437067A0, kTlsSlotOffset = 0x38, kScratchFrameVtable = 0x14258BCA8,
                   kScratchArenaBytes = 0x40000, kTlsBlockBytes = 0x100, kScratchFrameBytes = 0x38;
constexpr uint64_t kScratchFrameBaseOffset = 0x18, kScratchFrameCursorOffset = 0x20, kScratchFrameEndOffset = 0x28;
// The zero-initialised part of .data (the section table: virtual size 0x72A000, raw size 0x334800 at 0x14339B000, so the tail is
// 0x1436CF800..0x143AC5000): at process start Windows maps it zero, and PES's own start-up code (the allocator's malloc_init_hard, the C++
// static initializers, the engine singletons' first use) builds on that. The dump holds the dead game's runtime state there: the allocator's
// trees, the registries, every `if (cell == 0)` singleton and smart-pointer global (an initializer that assigns null into one releases the
// dead object it still names). The boot zeroes the whole tail.
constexpr uint64_t kZeroDataBegin = 0x1436CF800, kZeroDataEnd = 0x143AC5000;

void ZeroInitializedData(PesMemory& memory) {
  std::memset(memory.Image() + (kZeroDataBegin - PesMemory::kImageBase), 0, kZeroDataEnd - kZeroDataBegin);
}

// The scratch arena's frame, the TLS block that names it, and the TEB's TLS pointer: the state the thread's first engine phase reads.
void InstallScratchArena(PesMemory& memory) {
  const uint64_t tlsArray = memory.Alloc(8 * (static_cast<uint64_t>(memory.Read32(kTlsIndexVa)) + 1));
  const uint64_t block = memory.Alloc(kTlsBlockBytes), frame = memory.Alloc(kScratchFrameBytes), arena = memory.Alloc(kScratchArenaBytes);
  if (!tlsArray || !block || !frame || !arena) throw std::runtime_error("PES boot: the arena is full");
  memory.Write64(frame, kScratchFrameVtable);  // {vtable, 0, prev = 0, base, cursor = base, end, 0}
  memory.Write64(frame + kScratchFrameBaseOffset, arena);
  memory.Write64(frame + kScratchFrameCursorOffset, arena);
  memory.Write64(frame + kScratchFrameEndOffset, arena + kScratchArenaBytes);
  memory.Write64(block + kTlsSlotOffset, frame);
  memory.Write32(block + kTlsInitEpochOffset, kInitEpochStart);
  memory.Write64(tlsArray + 8 * static_cast<uint64_t>(memory.Read32(kTlsIndexVa)), block);
  memory.Write64(PesMemory::kTebVa + kTebTlsPointerOffset, tlsArray);
}

// The selected C++ static initializers (kSelectedInitializers), in table order; returns how many ran.
uint64_t RunStaticInitializers(PesMemory& memory) {
  uint64_t run = 0;
  for (const uint64_t entry : kSelectedInitializers) {
    const PesDispatch target = pes_dispatch_lookup(entry);
    if (target.fn) {
      memory.Call(target.fn, {});
      ++run;
    }
  }
  return run;
}

