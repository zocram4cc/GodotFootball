void Put(uint8_t* base, std::size_t off, const uint32_t* words, std::size_t n) {
  std::memcpy(base + off, words, n * sizeof(uint32_t));
}

// Q and T of a world holding the real call's entry state.
void Load(pes::PesWorld& world, const Row& r) {
  const int slot = static_cast<int>(r.head[0]);
  uint8_t* q = world.DecisionPlan(slot);
  uint8_t* t = world.DecisionTeam(slot);
  Put(q, 0, r.plan, 16);
  q[pes::kPlanRowOffset] = static_cast<uint8_t>(r.head[1]);
  q[pes::kPlanRowCountOffset] = static_cast<uint8_t>(r.head[2]);
  Put(q, pes::kPlanRowsOffset, r.rows, 12);
  Put(q, pes::kRetainedMode - 0x10, r.ret, 16);
  Put(q, pes::kPlanFacingOffset, r.man, 5);
  uint8_t* man = world.ManRecord(slot);
  std::memcpy(man + pes::kManFacingOffset, &r.man[0], 4);
  std::memcpy(man + pes::kManPosXOffset, &r.man[2], 12);
  t[pes::kDecisionTOutClassOffset] = static_cast<uint8_t>(r.head[3]);
}

void ExpectFrame(const pes::PesWorld& world, const Row& r, int row) {
  const uint8_t* f = world.TickFrameConst();
  constexpr std::size_t kOffsets[12] = {0, 4, 0x5C, 0x5E4, 0x14, 0x18, 0x1C, 0x2C, 0x30, 0x34, 0x54, 0x58};
  for (int k = 0; k < 12; ++k) {
    uint32_t v;
    std::memcpy(&v, f + kOffsets[k], 4);
    EXPECT_EQ(v, r.out[k]) << "row " << row << " F+0x" << std::hex << kOffsets[k];
  }
}

TEST(PesDecisionFrame, TheBuilderOverTheRealEntryStateReproducesTheRealFrame) {
  int row = 0;
  for (const Row& r : kRows) {
    pes::PesWorld world;
    for (int k = 0; k < pes::kSlotCount; ++k) world.BindSlot(k);
    pes::PesTrapExternals ext;
    Load(world, r);
    world.RunFrameBuilder(static_cast<int>(r.head[0]), ext);
    ExpectFrame(world, r, row);
    ++row;
  }
}

float AsFloat(uint32_t bits) {
  float f;
  std::memcpy(&f, &bits, sizeof f);
  return f;
}

// GF's mapping of an AI command into the plan: a plan the AI had (row count nonzero) is rebuilt from the target point, the speed and the
// gait row alone, and the builder's frame must come out the same as the real one.
TEST(PesDecisionFrame, ThePlanMappedFromTargetSpeedAndGaitReproducesTheRealFrame) {
  int row = 0, mapped = 0;
  for (const Row& r : kRows) {
    ++row;
    if (r.head[2] != 2) continue;  // a one-target plan: two rows, the leading one and the row in force
    ++mapped;
    pes::PesWorld world;
    for (int k = 0; k < pes::kSlotCount; ++k) world.BindSlot(k);
    pes::PesTrapExternals ext;
    Load(world, r);
    const int slot = static_cast<int>(r.head[0]);
    pes::PesDecision d;
    d.active = true;
    d.speedKmh = AsFloat(r.rows[4]);  // the row in force: Q+0x40C
    d.gaitRow = r.rows[5];
    std::memcpy(d.target, &r.plan[9], sizeof d.target);  // Q+0x24: the point index + 2
    world.RunDecisionFrame(slot, d, ext);
    ExpectFrame(world, r, row - 1);
    const uint8_t* q = world.DecisionPlan(slot);
    EXPECT_EQ(q[pes::kPlanIndexOffset], r.plan[0] >> 24) << "row " << row - 1 << " plan index";
    EXPECT_EQ(q[pes::kPlanPointCountOffset], r.plan[1] & 0xFF) << "row " << row - 1 << " plan point count";
    EXPECT_EQ(std::memcmp(q + pes::kPlanPointsOffset, r.plan + 2, 12), 0) << "row " << row - 1 << " plan point 0";
  }
  EXPECT_GT(mapped, 0);
}

