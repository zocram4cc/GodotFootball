#!/usr/bin/env python3
"""gen_trapconstant.py: the disk-to-runtime map of constant::Trap (PES FUN_141E67B70, vtable 0x142B53158 slot 2).

The constant objects of constant_player.bin are loaded by slot 2 of their class: it walks the object's offset tree (each u32
word is an offset from the object's start, 0 = null; FUN_141E823E0 turns it into a pointer) and copies leaves into the runtime
object. This script reads that function's Ghidra decompile and writes one row per store:

    {runtime offset, bytes, leaf byte offset, {u32 word indices of the offset chain from the root}}

Usage: gen_trapconstant.py DECOMPILE_TXT > src/sim/onthepitch/pestrapconstant_fields.inc
  (DECOMPILE_TXT: curl "http://127.0.0.1:8080/decompile_function?address=0x141e67b70" > file)
"""
import re
import sys

text = open(sys.argv[1]).read()
ROOT = "param_2"
env = {ROOT: ([], 4)}  # variable -> (chain of u32 word indices from the root, element bytes)


def num(s):
    s = s.strip()
    return int(s, 16) if s.startswith("0x") else int(s)


def scale(var):
    return env[var][1]


def source(expr):
    """expr -> (chain, byte offset of the leaf within the node)"""
    expr = expr.strip()
    m = re.fullmatch(r"\*(\w+)", expr)
    if m:
        return env[m.group(1)][0], 0
    m = re.fullmatch(r"(\w+)\[(\w+)\]", expr)
    if m:
        return env[m.group(1)][0], num(m.group(2)) * scale(m.group(1))
    m = re.fullmatch(r"\*\(undefined[14] \*\)\((\w+) \+ (\w+)\)", expr)
    if m:
        return env[m.group(1)][0], num(m.group(2)) * scale(m.group(1))
    m = re.fullmatch(r"\*\(undefined1 \*\)\(\(longlong\)param_2 \+ (\w+)\)", expr)
    if m:
        return [], num(m.group(1))
    raise SystemExit("unparsed source: " + expr)


rows = []
for line in text.splitlines():
    line = line.strip()
    m = re.fullmatch(r"(\w+) = \((undefined[14]) \*\)FUN_141e823e0\((.+?)(?:,param_2)?\);", line)
    if m:
        var, ty, arg = m.groups()
        chain, off = source(arg)
        if off % 4:
            raise SystemExit("pointer word not aligned: " + line)
        env[var] = (chain + [off // 4], 4 if ty == "undefined4" else 1)
        continue
    m = re.fullmatch(r"\*\((undefined[14]) \*\)\(param_1 \+ (\w+)\) = (.+);", line)
    if m:
        ty, dst, expr = m.groups()
        chain, off = source(expr)
        rows.append((num(dst), 4 if ty == "undefined4" else 1, off, chain))
        continue
    if "FUN_141e823e0" in line or "param_1 +" in line:
        raise SystemExit("unparsed line: " + line)

print("// Generated by tools/dev/translate/gen_trapconstant.py from FUN_141E67B70 (constant::Trap's slot-2 loader); do not edit.")
print("// {runtime offset, bytes, leaf byte offset, chain length, offset-word chain}")
for dst, size, off, chain in rows:
    print("{0x%X, %d, 0x%X, %d, {%s}}," % (dst, size, off, len(chain), ", ".join("0x%X" % w for w in chain)))
