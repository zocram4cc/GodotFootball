#!/usr/bin/env python3
"""gen_dispatch.py: the indirect-call dispatch table over a set of translated VAs.

The table is one translation unit, pes_dispatch_gen.cpp: the only file that names every translated function. The
pes_fn_<VA>.cpp TUs see only the pes_dispatch.hpp declarations, so adding a function recompiles that TU and this one.
gen_translated.py writes the committed table (src/pes/translated/pes_dispatch_gen.cpp); driver.py and snapdiff.py
write the same file into each diff build's tree and compile it with the closure.

Native targets (stubs.json "native_services", read through stubs.natives()): a PES VA the production table sends to a
GF-native implementation (src/pes/translated/pes_native.hpp) instead of a translated body. Only the committed table
carries them (gen_translated.py, --native here): the harness builds run PES's bytes for those VAs, as before.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stubs as stub_table  # noqa: E402


def norm(vas):
    return sorted({"0x" + v.lower().replace("0x", "").upper() for v in vas})


def natives():
    """{'0xVA': op} for every native service in the global stub table (stubs.json)."""
    return {"0x%X" % va: op for va, op in stub_table.natives().items()}


def text(vas, native=None):
    """The dispatch TU: each VA maps to its translated function or, when it is in `native` ({'0xVA': op}), to its
    GF-native service pes_native_<op>; a target outside the table aborts loudly."""
    vas = norm(vas)
    native = {"0x" + v.lower().replace("0x", "").upper(): op for v, op in (native or {}).items()}
    clash = sorted(set(vas) & set(native))
    if clash:
        raise SystemExit("gen_dispatch: %s both translated and a native service" % " ".join(clash))
    L = [
        "// Generated by tools/dev/translate/gen_dispatch.py: PES VA ->",
        "// translated-function table. Do not edit.",
        "#include <cstdio>",
        "#include <cstdlib>",
        '#include "pes_state.hpp"',
        '#include "pes_dispatch.hpp"',
    ]
    for v in vas:
        L.append("void pes_fn_%s(PesState& s);" % v[2:])
    for op in sorted(set(native.values())):
        L.append("void pes_native_%s(PesState& s);" % op)
    L.append("PesDispatch pes_dispatch_lookup(uint64_t t) {")
    L.append("  switch (t) {")
    for v in vas:
        L.append("    case 0x%sULL: return {pes_fn_%s};" % (v[2:], v[2:]))
    for v in sorted(native):
        L.append("    case 0x%sULL: return {pes_native_%s};" % (v[2:], native[v]))
    L.append("    default: return {0};")
    L.append("  }")
    L.append("}")
    L.append("void (*pes_dispatch_missing_handler)(uint64_t) = nullptr;")
    L.append("[[noreturn]] void pes_dispatch_missing(uint64_t t) {")
    L.append("  if (pes_dispatch_missing_handler) pes_dispatch_missing_handler(t);")
    L.append('  std::fprintf(stderr, "PES_DISPATCH_UNTRANSLATED: %#llx\\n",')
    L.append("               (unsigned long long)t);")
    L.append("  std::abort();")
    L.append("}")
    return "\n".join(L) + "\n"


def write(out, vas, native=None):
    """Write <out>/pes_dispatch_gen.cpp; returns the target count."""
    vas = norm(vas)
    with open(out.rstrip("/") + "/pes_dispatch_gen.cpp", "w") as f:
        f.write(text(vas, native))
    return len(vas) + len(native or {})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--vas", nargs="*", default=[])
    ap.add_argument("--native", action="store_true",
                    help="also route the stub table's native services to their GF-native implementations")
    args = ap.parse_args()
    n = write(args.out, args.vas, natives() if args.native else None)
    print("wrote %s/pes_dispatch_gen.cpp (%d targets)" % (args.out, n))


if __name__ == "__main__":
    sys.exit(main())
