#!/usr/bin/env python3
"""gen_dispatch.py: generate the indirect-call dispatch table (build tree only)."""
import argparse


def write(out, vas):
    """Write <out>/pes_dispatch_gen.hpp mapping each VA to its translated function; returns the target count."""
    vas = sorted({"0x" + v.lower().replace("0x", "").upper() for v in vas})
    L = []
    L.append("// Generated by tools/dev/translate/gen_dispatch.py: PES VA ->")
    L.append("// translated-function table. Build tree only; never committed.")
    L.append("#pragma once")
    L.append("#include <cstdio>")
    L.append("#include <cstdlib>")
    L.append('#include "pes_state.hpp"')
    L.append('#include "pes_dispatch.hpp"')
    for v in vas:
        L.append("void pes_fn_%s(PesState& s);" % v[2:])
    L.append("inline PesDispatch pes_dispatch_lookup(uint64_t t) {")
    L.append("  switch (t) {")
    for v in vas:
        L.append("    case 0x%sULL: return {pes_fn_%s};" % (v[2:], v[2:]))
    L.append("    default: return {0};")
    L.append("  }")
    L.append("}")
    L.append("[[noreturn]] inline void pes_dispatch_missing(uint64_t t) {")
    L.append('  std::fprintf(stderr, "PES_DISPATCH_UNTRANSLATED: %#llx\\n",')
    L.append("               (unsigned long long)t);")
    L.append("  std::abort();")
    L.append("}")
    with open(out.rstrip("/") + "/pes_dispatch_gen.hpp", "w") as f:
        f.write("\n".join(L) + "\n")
    return len(vas)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--vas", nargs="*", default=[])
    args = ap.parse_args()
    n = write(args.out, args.vas)
    print("wrote %s/pes_dispatch_gen.hpp (%d targets)" % (args.out, n))


if __name__ == "__main__":
    import sys
    sys.exit(main())
