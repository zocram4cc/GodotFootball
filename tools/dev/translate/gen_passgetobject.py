#!/usr/bin/env python3
"""gen_passgetobject.py: the constructed state of PES's ActionPassGet object (FUN_14091DAB0, vtable 0x1426301E0).

The object is the AI action `match::player::ActionPassGet`: the action base (FUN_140512CA0, up to +0x70), the route manager at +0x70
(FUN_14091E390: the seven route objects BallFollow +0x00, MoveStraightTrapStop +0x610, MovePositionAdjust +0xC68, NextPlay +0x11F8,
BallAvoid +0x1828, TargetEnemy +0x1E00, ThrowIn +0x24C0) and the counters behind it, to +0x2B88. The stores are PES's own bytes, run by
unicorn on the flat image over a zeroed buffer (nothing is typed here); the one call outside the object's own code, the host memset
(FUN_1415A1720), is modelled. A cell holding a heap pointer the run could not build is listed in the header comment and NOT built.

Output rows: {offset from the object, kind, value}; kind 0 = u64 constant (ints, floats as bits, image VAs), kind 1 = a pointer into the
object (value = byte offset from its start).

Usage (harness Python with unicorn): gen_passgetobject.py IMAGE > src/sim/onthepitch/pespassgetobject_stores.inc
       gen_passgetobject.py IMAGE --check FILE      # exit 1 when FILE differs from the regenerated table
"""
import struct
import sys

from unicorn import UC_ARCH_X86, UC_HOOK_CODE, UC_MODE_64, Uc, UcError
from unicorn.x86_const import UC_X86_REG_R8, UC_X86_REG_RAX, UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_RIP, UC_X86_REG_RSP

BASE = 0x140000000
CTOR = 0x14091DAB0
SIZE = 0x2B90
T, HEAP, STACK, RET = 0x50000000, 0x60000000, 0x70000000, 0x70000000
MEMSET = 0x1415A1720  # FUN_1415A1720(dst, byte, n): a jmp through the import table to the host's memset


def run(image):
    data = open(image, "rb").read()
    uc = Uc(UC_ARCH_X86, UC_MODE_64)
    uc.mem_map(BASE, (len(data) + 0xFFF) & ~0xFFF)
    uc.mem_write(BASE, data)
    uc.mem_map(T, 0x10000)
    uc.mem_map(HEAP, 0x100000)
    uc.mem_map(STACK, 0x100000)
    uc.mem_write(RET, b"\xf4")

    def hook(uc, addr, size, _):
        if addr != MEMSET:
            return
        dst, val, n = (uc.reg_read(r) for r in (UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_R8))
        uc.mem_write(dst, bytes([val & 0xFF]) * n)
        rsp = uc.reg_read(UC_X86_REG_RSP)
        ret = struct.unpack("<Q", uc.mem_read(rsp, 8))[0]
        uc.reg_write(UC_X86_REG_RSP, rsp + 8)
        uc.reg_write(UC_X86_REG_RIP, ret)

    uc.hook_add(UC_HOOK_CODE, hook)
    sp = STACK + 0x80000 - 8
    uc.mem_write(sp, struct.pack("<Q", RET))
    uc.reg_write(UC_X86_REG_RSP, sp)
    uc.reg_write(UC_X86_REG_RCX, T)
    try:
        uc.emu_start(CTOR, RET, count=3000000)
    except UcError as e:
        sys.exit("emulation failed: %s at %#x" % (e, uc.reg_read(UC_X86_REG_RIP)))
    return bytes(uc.mem_read(T, SIZE))


def table(image):
    obj = run(image)
    rows, heap = [], []
    for off in range(0, SIZE, 8):
        v = struct.unpack_from("<Q", obj, off)[0]
        if v == 0:
            continue
        if HEAP <= v < HEAP + 0x100000:
            heap.append(off)
        elif T <= v < T + SIZE:
            rows.append((off, 1, v - T))
        else:
            rows.append((off, 0, v))
    out = ["// Generated by tools/dev/translate/gen_passgetobject.py from FUN_14091DAB0 (ActionPassGet's constructor); do not edit.",
           "// {offset from the object, kind (0 = u64 constant, 1 = pointer into the object), value (kind 1: offset from the object's start)}",
           "// Heap cells not built: " + " ".join("0x%X" % o for o in heap)]
    out += ["{0x%X, %d, 0x%XULL}," % r for r in rows]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = table(sys.argv[1])
    if len(sys.argv) > 3 and sys.argv[2] == "--check":
        sys.exit(0 if open(sys.argv[3]).read() == text else 1)
    sys.stdout.write(text)
