#!/usr/bin/env python3
"""gen_animplugin.py: the stores of PES's AnimPlugin constructor FUN_141B158F0 (the 0x1378-byte object O1 of the Trap tick).

The constructor builds nine embedded anime-layer objects with their own constructors and a pointer array that points back into
the object (docs/ports/pes-port-TrapTick3.md). It is straight-line stores plus calls this script models; the stores themselves
are PES's own bytes, run by unicorn on the flat image (nothing is typed here). Calls the run cannot execute:

  FUN_142399230  (a parameter-block instantiator over the heap)   returns a heap pointer; the cells holding one are NOT built
  FUN_142398860  (the plugin's name registration)                 no store into the object
  FUN_142397EA0, FUN_1403CF7E0 (the base-class initialiser, heap) no-ops: the base fields they set are NOT built
  FUN_1415A178C  (jmp [0x142530208]: the host's cosf, CONFIRMED: cap +0x88 = cosf(DAT) on layers 5/6/7/8 of seq6634)

Output rows: {offset, kind, value}; kind 0 = u64 constant (ints, floats as bits, image VAs), kind 1 = a pointer into the object (value = byte
offset from its start). The run's own heap cells are omitted and listed in the header comment.

Usage (harness Python with unicorn): gen_animplugin.py IMAGE > src/sim/onthepitch/pesanimplugin_stores.inc
       gen_animplugin.py IMAGE --check FILE      # exit 1 when FILE differs from the regenerated table
"""
import math
import struct
import sys

from unicorn import UC_ARCH_X86, UC_HOOK_CODE, UC_MODE_64, Uc, UcError
from unicorn.x86_const import (UC_X86_REG_R8, UC_X86_REG_R9, UC_X86_REG_RAX, UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_RIP,
                               UC_X86_REG_RSP, UC_X86_REG_XMM0)

BASE = 0x140000000
CTOR = 0x141B158F0
SIZE = 0x1378
O1, HEAP, STACK, RET = 0x50000000, 0x60000000, 0x70000000, 0x70000000
ALLOC, NOP = {0x142399230}, {0x142398860, 0x142397EA0, 0x1403CF7E0}
COSF = 0x1415A178C


def run(image):
    data = open(image, "rb").read()
    uc = Uc(UC_ARCH_X86, UC_MODE_64)
    uc.mem_map(BASE, (len(data) + 0xFFF) & ~0xFFF)
    uc.mem_write(BASE, data)
    uc.mem_map(O1, 0x10000)
    uc.mem_map(HEAP, 0x100000)
    uc.mem_map(STACK, 0x100000)
    uc.mem_write(RET, b"\xf4")
    bump = [HEAP]

    def hook(uc, addr, size, _):
        if addr not in ALLOC and addr not in NOP and addr != COSF:
            return
        rsp = uc.reg_read(UC_X86_REG_RSP)
        ret = struct.unpack("<Q", uc.mem_read(rsp, 8))[0]
        if addr in ALLOC:
            uc.reg_write(UC_X86_REG_RAX, bump[0])
            bump[0] += 0x100
        elif addr == COSF:
            x = struct.unpack("<f", bytes(uc.reg_read(UC_X86_REG_XMM0).to_bytes(16, "little"))[:4])[0]
            uc.reg_write(UC_X86_REG_XMM0, struct.unpack("<I", struct.pack("<f", math.cos(x)))[0])
        uc.reg_write(UC_X86_REG_RSP, rsp + 8)
        uc.reg_write(UC_X86_REG_RIP, ret)

    uc.hook_add(UC_HOOK_CODE, hook)
    sp = STACK + 0x80000 - 8
    uc.mem_write(sp, struct.pack("<Q", RET))
    uc.reg_write(UC_X86_REG_RSP, sp)
    # param_1 = O1; param_2 / param_3 / param_4 are heap objects the stores only copy (param_4 lands at +0x1370: not built)
    for reg, v in ((UC_X86_REG_RCX, O1), (UC_X86_REG_RDX, 0), (UC_X86_REG_R8, 0), (UC_X86_REG_R9, 0)):
        uc.reg_write(reg, v)
    try:
        uc.emu_start(CTOR, RET, count=3000000)
    except UcError as e:
        sys.exit("emulation failed: %s at %#x" % (e, uc.reg_read(UC_X86_REG_RIP)))
    return bytes(uc.mem_read(O1, SIZE))


def table(image):
    obj = run(image)
    rows, heap = [], []
    for off in range(0, SIZE, 8):
        v = struct.unpack_from("<Q", obj, off)[0]
        if v == 0:
            continue
        if HEAP <= v < HEAP + 0x100000:
            heap.append(off)
        elif O1 <= v < O1 + SIZE:
            rows.append((off, 1, v - O1))
        else:
            rows.append((off, 0, v))
    out = ["// Generated by tools/dev/translate/gen_animplugin.py from FUN_141B158F0 (the AnimPlugin constructor); do not edit.",
           "// {offset, kind (0 = u64 constant, 1 = pointer into the object), value (kind 1: offset from the object's start)}",
           "// Heap cells not built (a parameter-block pointer, FUN_142399230): " + " ".join("0x%X" % o for o in heap)]
    out += ["{0x%X, %d, 0x%XULL}," % r for r in rows]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = table(sys.argv[1])
    if len(sys.argv) > 3 and sys.argv[2] == "--check":
        sys.exit(0 if open(sys.argv[3]).read() == text else 1)
    sys.stdout.write(text)
