#!/usr/bin/env python3
"""gen_actiontable.py: the stores of PES's per-action object table at P+0xC40 (FUN_1406E0540 -> FUN_1406DF630 + FUN_1406D9040).

P+0xC40 is the action table object: vtable PTR_FUN_1425E34C8 at +0, the ~190 action objects built by FUN_1406DF630 from +8 (to P+0x1AA0:
MOVE id 2 at P+0xC50, the Trap action id 7 at P+0xC78), and the id -> object pointer array FUN_1406D9040 fills at +0x1528 (94 slots, zeroed
first; FUN_1406D9010(table, id) returns slot[id] or slot[1]). FUN_1406D9040 ends by calling every non-null slot's vtable +8 with rcx = the
object. The stores are PES's own bytes, run by unicorn on the flat image (nothing is typed here); the calls outside the table's own code are
modelled below. Cells holding a heap pointer the run could not build are listed in the header comment and NOT built.

Output rows: {offset from P+0xC40, kind, value}; kind 0 = u64 constant (ints, floats as bits, image VAs), kind 1 = a pointer into the table object
(value = byte offset from its start).

Usage (harness Python with unicorn): gen_actiontable.py IMAGE > src/sim/onthepitch/pesactiontable_stores.inc
       gen_actiontable.py IMAGE --check FILE      # exit 1 when FILE differs from the regenerated table
"""
import struct
import sys

from unicorn import UC_ARCH_X86, UC_HOOK_CODE, UC_MODE_64, Uc, UcError
from unicorn.x86_const import UC_X86_REG_R8, UC_X86_REG_RAX, UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_RIP, UC_X86_REG_RSP

BASE = 0x140000000
CTOR_OBJECTS, CTOR_TABLE = 0x1406DF630, 0x1406D9040
SIZE = 0x1818
T, HEAP, STACK, RET = 0x50000000, 0x60000000, 0x70000000, 0x70000000
ALLOC = set()  # heap instantiators the run returns a bump pointer for
NOP = set()  # calls with no store into the table
MEMSET = 0x1415A1720  # FUN_1415A1720(dst, byte, n): a jmp through the import table to the host's memset


def run(image):
    data = open(image, "rb").read()
    uc = Uc(UC_ARCH_X86, UC_MODE_64)
    uc.mem_map(BASE, (len(data) + 0xFFF) & ~0xFFF)
    uc.mem_write(BASE, data)
    uc.mem_map(T, 0x10000)
    uc.mem_map(HEAP, 0x100000)
    uc.mem_map(STACK, 0x100000)
    uc.mem_write(RET, b"\xf4")
    bump = [HEAP]
    seen = []

    def hook(uc, addr, size, _):
        if addr == MEMSET:
            dst, val, n = (uc.reg_read(r) for r in (UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_R8))
            uc.mem_write(dst, bytes([val & 0xFF]) * n)
        elif addr not in ALLOC and addr not in NOP:
            return
        rsp = uc.reg_read(UC_X86_REG_RSP)
        ret = struct.unpack("<Q", uc.mem_read(rsp, 8))[0]
        if addr in ALLOC:
            uc.reg_write(UC_X86_REG_RAX, bump[0])
            bump[0] += 0x100
        uc.reg_write(UC_X86_REG_RSP, rsp + 8)
        uc.reg_write(UC_X86_REG_RIP, ret)

    uc.hook_add(UC_HOOK_CODE, hook)

    def call(fn, rcx):
        sp = STACK + 0x80000 - 8
        uc.mem_write(sp, struct.pack("<Q", RET))
        uc.reg_write(UC_X86_REG_RSP, sp)
        uc.reg_write(UC_X86_REG_RCX, rcx)
        uc.emu_start(fn, RET, count=3000000)

    # FUN_1406E0540: `lea rax,[vtable]` (48 8D 05) at 0x1406E0556? located by scanning the function's first bytes
    fn = data[0x1406E0540 - BASE:0x1406E0540 - BASE + 0x60]
    i = fn.find(b"\x48\x8d\x05", 0x10)
    vt = 0x1406E0540 + i + 7 + struct.unpack_from("<i", fn, i + 3)[0]
    try:
        call(CTOR_OBJECTS, T + 8)
        uc.mem_write(T, struct.pack("<Q", vt))
        call(CTOR_TABLE, T)
    except UcError as e:
        sys.exit("emulation failed: %s at %#x" % (e, uc.reg_read(UC_X86_REG_RIP)))
    return bytes(uc.mem_read(T, SIZE))


def table(image):
    obj = run(image)
    rows, heap = [], []
    for off in range(0, SIZE, 8):
        v = struct.unpack_from("<Q", obj, off)[0]
        if v == 0:
            continue
        if HEAP <= v < HEAP + 0x100000:
            heap.append(off)
        elif T <= v < T + SIZE:
            rows.append((off, 1, v - T))
        else:
            rows.append((off, 0, v))
    out = ["// Generated by tools/dev/translate/gen_actiontable.py from FUN_1406DF630 + FUN_1406D9040 (the action table at P+0xC40); do not edit.",
           "// {offset from P+0xC40, kind (0 = u64 constant, 1 = pointer into the table object), value (kind 1: offset from the object's start)}",
           "// Heap cells not built: " + " ".join("0x%X" % o for o in heap)]
    out += ["{0x%X, %d, 0x%XULL}," % r for r in rows]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = table(sys.argv[1])
    if len(sys.argv) > 3 and sys.argv[2] == "--check":
        sys.exit(0 if open(sys.argv[3]).read() == text else 1)
    sys.stdout.write(text)
