import os
import shutil
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


joins = _load("joins", os.path.join(HERE, "joins.py"))
ledger = _load("ledger_gen", os.path.join(HERE, "..", "ledger.py"))
U = _load("universe", os.path.join(HERE, "universe.py"))


def listing(text):
    """Bridge/capstone-format listing lines into universe (insns, order)."""
    insns = {}
    for line in text.strip().splitlines():
        addr, _, body = line.partition(":")
        insns[int(addr.strip(), 16)] = body.strip()
    return insns, sorted(insns)


def fake_img(offset, payload):
    import io
    buf = bytearray(b"\x00" * (offset + len(payload)))
    buf[offset:offset + len(payload)] = payload
    return io.BytesIO(bytes(buf))

IN_SCOPE = {"scope": "in", "walked": True}


class JoinFixture(unittest.TestCase):
    def setUp(self):
        self.repo = tempfile.mkdtemp(prefix="ledger-fixture-")
        self.addCleanup(shutil.rmtree, self.repo, True)
        # 141AF3CA0: committed in the layer and recorded bit-exact, and also cited by a stand-in.
        self.write("src/pes/translated/gameplay/pes_fn_141AF3CA0.cpp",
                   "// Generated by tools/dev/translate/xlate.py: PES function 0x141AF3CA0.\n"
                   "// image constant @ 0x14233CCCC (4 bytes)\n")
        # 141EB5E70: committed only as a closure member (never recorded), cited by a stand-in too.
        self.write("src/pes/translated/closure/pes_fn_141EB5E70.cpp", "// fixture\n")
        self.write("src/gf_stub.cpp",
                   "// ponytail: stand-in for 0x141AF3CA0 until the PES site lands\n"
                   "// ponytail: stand-in for 0x141EB5E70 until the PES site lands\n"
                   "// ponytail: stand-in for 0x142999999 until the PES site lands\n")
        self.write("docs/re/fixture.md", "**CONFIRMED** the flag is set at 0x141EB5E70.\n")
        self.write("tools/dev/translate/results_core.json", json.dumps({"results": [
            {"va": "0x141AF3CA0", "translated": True, "diffed": True, "synthetic": False},
            {"va": "0x141EB5E70", "translated": True, "diffed": False},
            {"va": "0x14211BF10", "translated": True, "diffed": False, "proven": True},
            {"va": "0x14211BF20", "translated": True, "diffed": True, "synthetic": True},
        ]}))

    def write(self, rel, text):
        path = os.path.join(self.repo, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)

    def build(self, **kw):
        return joins.build(self.repo, **kw)


class JoinTests(JoinFixture):
    def test_a_committed_and_recorded_va_is_diffed(self):
        j = self.build()
        self.assertIn("141AF3CA0", j["diffed"])
        self.assertEqual(ledger.classify("141AF3CA0", IN_SCOPE, j, {}), "diffed")

    def test_a_committed_translations_banner_is_not_a_gf_port(self):
        j = self.build()
        self.assertNotIn("14233CCCC", j["ports"])


    def test_a_committed_va_with_no_bit_exact_record_is_translated(self):
        j = self.build()
        self.assertEqual(j["translated"]["141EB5E70"], "src/pes/translated/closure/pes_fn_141EB5E70.cpp")
        self.assertEqual(ledger.classify("141EB5E70", IN_SCOPE, j, {}), "translated")

    def test_a_proven_snapdiff_record_is_recorded_bit_exact(self):
        j = self.build()
        self.assertEqual(j["diffed"]["14211BF10"], "tools/dev/translate/results_core.json")
        self.assertEqual(ledger.classify("14211BF10", IN_SCOPE, j, {}), "diffed")

    def test_a_synthetic_proof_is_diffed_and_flagged(self):
        j = self.build()
        self.assertEqual(ledger.classify("14211BF20", IN_SCOPE, j, {}), "diffed")
        self.assertIn("14211BF20", j["synthetic"])
        self.assertNotIn("141AF3CA0", j["synthetic"])
        self.assertEqual(ledger.proof_label("14211BF20", "diffed", j), "synthetic")
        self.assertEqual(ledger.proof_label("141AF3CA0", "diffed", j), "real")
        self.assertEqual(ledger.proof_label("141EB5E70", "translated", j), "closure")

    def test_recorded_and_translated_beat_a_stand_in_citation(self):
        j = self.build()
        self.assertEqual(ledger.classify("141EB5E70", IN_SCOPE, j, {}), "translated")
        self.assertEqual(ledger.classify("142999999", IN_SCOPE, j, {}), "stand-in")

    def test_a_141_va_in_a_doc_gets_its_verdict(self):
        j = self.build()
        self.assertEqual(j["decode"]["141EB5E70"]["verdict"], "CONFIRMED")
        self.assertIn("141EB5E70", j["ports"])

    def test_a_bare_run_keeps_the_committed_spec_map_and_bridge_list(self):
        carried = {"diffed": {"140A3A500": "tools/dev/diffharness/specs/band.json",
                              "141111111": "tools/dev/translate/results.json"},
                   "funclist": ["141AF3CA0"]}
        j = self.build(carried=carried)
        self.assertEqual(j["diffed"]["140A3A500"], "tools/dev/diffharness/specs/band.json")
        self.assertNotIn("141111111", j["diffed"])  # results-sourced entries are re-read, never carried
        self.assertEqual(j["funclist"], ["141AF3CA0"])

    def test_a_spec_map_entry_outranks_its_recorded_source(self):
        j = self.build(diff_map={"141AF3CA0": "tools/dev/diffharness/specs/band.json"})
        self.assertEqual(j["diffed"]["141AF3CA0"], "tools/dev/diffharness/specs/band.json")
        self.assertNotIn("141AF3CA0", j["synthetic"])


class HistoryTests(unittest.TestCase):
    def test_regeneration_appends_one_row_per_count_change(self):
        cur = {"in_total": 3, "ported": 1}
        rows, appended = ledger.append_if_changed([], cur, "abc123", "2026-11-18")
        self.assertTrue(appended)
        self.assertEqual(len(rows), 1)
        rows, appended = ledger.append_if_changed(rows, dict(cur), "def456", "2026-11-19")
        self.assertFalse(appended)
        self.assertEqual(len(rows), 1)
        rows, appended = ledger.append_if_changed(rows, {"in_total": 3, "ported": 2}, "def456", "2026-11-19")
        self.assertTrue(appended)
        self.assertEqual(len(rows), 2)

    def test_a_history_behind_the_counts_fails_the_check(self):
        rows = [{"base": "a", "date": "d", "in_total": "3", "ported": "1"}]
        self.assertTrue(ledger.history_current(rows, {"in_total": 3, "ported": 1}))
        self.assertFalse(ledger.history_current(rows, {"in_total": 3, "ported": 2}))
        self.assertFalse(ledger.history_current([], {"in_total": 3, "ported": 1}))

    def test_a_delta_line_names_each_status_with_its_change(self):
        prev = {"base": "a", "date": "d", "ported": "1", "translated": "0"}
        cur = {"base": "b", "date": "e", "ported": "1", "translated": "5"}
        lines = ledger.delta_lines(prev, cur, ["ported", "translated"])
        self.assertEqual(len(lines), 2)
        self.assertIn("translated", lines[1])
        self.assertIn("+5", lines[1])
        self.assertIn("+0", lines[0])


class JumpTableTests(unittest.TestCase):
    R13_LISTING = """
141a894fb: LEA R13, [0x140000000]
141a89560: CMP EAX, 5
141a89563: JA 0x141a89956
141a89569: MOV EDX, dword ptr [R13 + RAX*0x4 + 0x1000]
141a89571: ADD RDX, R13
141a89574: JMP RDX
141a89576: CALL 0x140002000
"""

    def r13_table(self):
        import struct
        insns, order = listing(self.R13_LISTING)
        rva_fall = 0x141A89576 - 0x140000000
        return U.jump_tables(insns, order,
                             fake_img(0x1000, struct.pack("<6I", rva_fall, *[0x2000] * 5)))

    def test_r13_absolute_table_with_bare_cmp_bound_resolves(self):
        self.assertEqual(self.r13_table(), {0x141A89574: [0x140002000, 0x141A89576]})

    def test_table_fallthrough_chunk_is_walked(self):
        insns, order = listing(self.R13_LISTING)
        tbl = self.r13_table()
        pos = {a: i for i, a in enumerate(order)}
        body, calls, _tails, _ext, _ind, _drefs, hits = U.closure(
            0x141A894FB, insns, order, pos, set(), tbl)
        self.assertEqual(hits, 1)
        self.assertIn(0x141A89576, body)
        self.assertIn(0x140002000, calls)

    def test_rbase_table_with_hex_cmp_bound_still_resolves(self):
        import struct
        insns, order = listing("""
1406ba800: LEA RBX, [0x140000000]
1406ba810: CMP ECX, 0x6
1406ba814: MOV EAX, dword ptr [RBX + RDI*0x4 + 0x1000]
1406ba818: JMP RAX
""")
        tbl = U.jump_tables(insns, order,
                            fake_img(0x1000, struct.pack("<7I", *[0x3000] * 7)))
        self.assertEqual(tbl, {0x1406BA818: [0x140003000]})


class DtableTests(unittest.TestCase):
    def test_runs_of_finds_code_pointer_runs(self):
        C = 0x140000000
        vals = [C + 0x1000, C + 0x2000, C + 0x3000, 0,
                C + 0x4000, C + 0x5000, C + 0x6000, 0x143D14000]
        self.assertEqual(U.runs_of(vals, 0x142B00000),
                         {0x142B00000: [C + 0x1000, C + 0x2000, C + 0x3000],
                          0x142B00020: [C + 0x4000, C + 0x5000, C + 0x6000]})

    def test_short_runs_and_non_code_ignored(self):
        C = 0x140000000
        self.assertEqual(U.runs_of([C + 1, C + 2], 0x142B0), {})
        self.assertEqual(U.runs_of([0, 1, 2], 0x142B0), {})

    def test_dtable_callees_vtable_kind_wins(self):
        runs = {0x142B00000: [0x140001000, 0x140002000, 0x140003000]}
        DTN = {m: b for b, ss in runs.items() for m in ss}
        DTN.update({b: b for b in runs})
        callees = {0x140001000: "vtable"}
        for s, k in U.dtable_callees({0x142B00000, 0xDEADBEEF}, DTN, runs,
                                       {0x140001000}).items():
            callees.setdefault(s, k)
        self.assertEqual(callees,
                         {0x140001000: "vtable", 0x140002000: "dtable",
                          0x140003000: "dtable"})

    def test_lea_refs_only_takes_addresses(self):
        insns, _order = listing("""
140000000: LEA RAX, [0x142b00000]
140000007: MOV RCX, [0x142b00010]
14000000e: CALL 0x140002000
""")
        self.assertEqual(U.lea_refs(insns), {0x142B00000})

    def test_ptr_runs_skips_oversize_runs(self):
        import struct
        C = 0x140000000
        small = struct.pack("<3Q", C + 0x1000, C + 0x2000, C + 0x3000)
        big = struct.pack("<%dQ" % (U.MAX_DTABLE + 1),
                          *([C + 0x4000] * (U.MAX_DTABLE + 1)))
        img = fake_img(0x100, small + b"\x00" * 8 + big)
        import unittest.mock as mock
        with mock.patch.object(U, "RDATA_LO", 0x140000000), \
             mock.patch.object(U, "RDATA_HI", 0x140000000 + 0x100 + len(small) + 8 + len(big)), \
             mock.patch.object(U, "CODE_LO", 0x140000000), \
             mock.patch.object(U, "CODE_HI", 0x143000000):
            got = U.ptr_runs(img)
        self.assertEqual(got, {0x140000100: [C + 0x1000, C + 0x2000, C + 0x3000]})


class ThunkTailTests(unittest.TestCase):
    def test_thunk_body_records_tail_target(self):
        insns, order = listing("14071d760: JMP 0x14071d770")
        _body, _calls, tails, _ext, _ind, _drefs, _hits = U.closure(
            0x14071D760, insns, order, {0x14071D760: 0}, set(), {})
        self.assertEqual(tails, [0x14071D770])

    def test_missing_direct_callees_listed_for_requeue(self):
        funcs = {
            "00000001": {"scope": "in", "walked": True,
                          "callees": {"00000002": "direct", "00000003": "table",
                                       "00000009": "tail"}},
            "0000000A": {"scope": "out", "walked": True,
                          "callees": {"0000000B": "direct"}},
            "0000000C": {"scope": "in", "walked": False,
                          "callees": {"0000000D": "direct"}},
        }
        self.assertEqual(U.missing_callees(funcs, "in"),
                         [("00000001", "00000002", "direct"),
                          ("00000001", "00000009", "tail")])

class SeedDecodeTests(unittest.TestCase):
    def test_swallowed_seed_redecodes_from_itself(self):
        import struct
        img = fake_img(0x1000, struct.pack("<2I", 0xE8, 0) + b"\xc3")
        got = U.seed_decode(0x140001000, 0x140000000, "root", img, [0x14000000])
        self.assertIsNotNone(got)
        insns, order = got
        self.assertEqual(order[0], 0x140001000)
        self.assertIn("CALL", insns[0x140001000])

    def test_non_seed_or_matching_entry_keeps_listing(self):
        self.assertIsNone(U.seed_decode(0x140001000, 0x140001000, "root", None, []))
        self.assertIsNone(U.seed_decode(0x140001000, 0x140000000, "direct", None, []))


